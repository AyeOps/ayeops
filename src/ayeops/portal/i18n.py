def esc(value: object) -> str:
    return escape(str(value), quote=True)


def fill(template: str, lang: str, values: dict[str, Any]) -> str:
    return template.format(
        **{key: value[lang] if isinstance(value, dict) else value for key, value in values.items()}
    )


def tr(key: str, **values: Any) -> Text:
    entry = STRINGS[key]
    return {lang: fill(entry[lang], lang, values) for lang in LANGS}


def counted(key: str, count: int) -> Text:
    entry = STRINGS[key]
    texts = {}
    for lang in LANGS:
        forms = entry[lang].split("|")
        texts[lang] = forms[min(plural_index(lang, count), len(forms) - 1)].format(n=count)
    return texts


def same(text: str) -> Text:
    return dict.fromkeys(LANGS, text)


def lookup(prefix: str, word: str) -> Text:
    return tr(f"{prefix}.{word}") if f"{prefix}.{word}" in STRINGS else same(word)


def join(parts: list[Text], sep: str) -> Text:
    return {lang: sep.join(part[lang] for part in parts) for lang in LANGS}


def as_text(value: Any) -> Text:
    return localized(value)


def both(value: Any, tag: str = "span") -> str:
    text = as_text(value)
    if len(set(text.values())) == 1:
        return esc(text[DEFAULT_LANG])
    if tag == "span":
        return "".join(
            f'<span lang="{lang}" data-l="{lang}">{esc(text[lang])}</span>' for lang in LANGS
        )
    return "".join(f'<{tag} data-l="{lang}">{esc(text[lang])}</{tag}>' for lang in LANGS)


def markup(parts: Text) -> str:
    if len(set(parts.values())) == 1:
        return parts[DEFAULT_LANG]
    return "".join(f'<span lang="{lang}" data-l="{lang}">{parts[lang]}</span>' for lang in LANGS)


def attrs(**values: Any) -> str:
    texts = {name.replace("_", "-"): as_text(value) for name, value in values.items()}
    shown = "".join(f' {name}="{esc(text[DEFAULT_LANG])}"' for name, text in texts.items())
    varying = {name: text for name, text in texts.items() if len(set(text.values())) > 1}
    if not varying:
        return shown
    blob = json.dumps(varying, ensure_ascii=False, sort_keys=True, separators=(",", ":"))
    return f'{shown} data-i18n="{esc(blob)}"'


def text_attr(value: Any) -> str:
    text = as_text(value)
    if len(set(text.values())) == 1:
        return ""
    blob = json.dumps(text, ensure_ascii=False, sort_keys=True, separators=(",", ":"))
    return f' data-i18n-text="{esc(blob)}"'


def searchable(*values: Any) -> str:
    return " ".join(dict.fromkeys(as_text(value)[lang] for value in values for lang in LANGS))


def lang_css() -> str:
    return "".join(
        f'html[data-lang="{lang}"] [data-l]:not([data-l="{lang}"]){{display:none}}'
        for lang in LANGS
    )


def lang_boot() -> str:
    allowed = json.dumps(list(LANGS))
    return (
        "<script>try{var l=localStorage.getItem('aye-lang');"
        f"if({allowed}.indexOf(l)>=0){{document.documentElement.lang=l;"
        "document.documentElement.dataset.lang=l}}catch(e){}</script>"
    )


def js_strings() -> dict[str, Text]:
    keys = [key for key in STRINGS if key.startswith(("js.", "diagram."))]
    return {lang: {key: STRINGS[key][lang] for key in keys} for lang in LANGS}


def i18n_json() -> str:
    text = json.dumps(js_strings(), ensure_ascii=False, sort_keys=True, separators=(",", ":"))
    return text.replace("</", "<\\/")
