ENV = re.compile(r"\$\{(AYE_[A-Z0-9_]+)")


def template_env(module_dir: Path) -> set[str]:
    return {
        name
        for path in module_dir.rglob("*.j2")
        for name in ENV.findall(path.read_text(encoding="utf-8"))
    }


def declared(spec: dict[str, Any]) -> set[str]:
    names = {
        env
        for entry in [*(spec.get("permissions") or []), *(spec.get("generated") or [])]
        for env in entry["env"]
    }
    return {name for name in names if "{{" not in name}


def test_every_variable_a_module_template_reads_is_declared_by_that_module() -> None:
    missing = {
        module.name: sorted(template_env(module.path) - declared(module.spec))
        for module in load_modules().values()
    }
    assert {name: names for name, names in missing.items() if names} == {}


def test_every_variable_of_env_example_is_declared_somewhere() -> None:
    every = set().union(*(declared(module.spec) for module in load_modules().values()))
    manifest = manifest_from(example_data())
    modules = load_modules()
    for host in manifest.hosts:
        for name in manifest.host_modules(host):
            every.update(e for c in credentials(manifest, modules, host, name) for e in c.env)
    listed = {
        line.split("=", 1)[0]
        for line in (ROOT / ".env.example").read_text(encoding="utf-8").splitlines()
        if "=" in line
    }
    assert sorted(listed - every) == []


