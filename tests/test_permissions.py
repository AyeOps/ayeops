def edge_with(data: dict[str, Any], module: str, settings: dict[str, Any]) -> list[str]:
    data["hosts"]["edge"]["modules"][module] = settings
    found = credentials(manifest_from(data), load_modules(), "edge", module)
    return [f"{c.issuer}|{c.credential}|{','.join(c.env)}|{' / '.join(c.grants)}" for c in found]


@pytest.mark.parametrize(
    ("append_only", "tail"),
    [(False, "restic deletes its lock files, prune deletes packs"), (True, "lock files")],
)
def test_an_s3_target_needs_a_key_for_one_bucket_prefix(append_only: bool, tail: str) -> None:
    target = {"url": "s3:https://s3.example/bucket/edge", "append_only": append_only}
    found = edge_with(
        example_data(), "offsite", {"source": "/var/backups/x.dump", "target": target}
    )
    assert len(found) == 1
    issuer, _, env, grants = found[0].split("|")
    assert issuer == "S3 provider of s3:https://s3.example/bucket/edge"
    assert env == "AYE_OFFSITE_ACCESS_KEY_ID,AYE_OFFSITE_SECRET_ACCESS_KEY"
    assert grants.endswith(tail)


def test_a_host_target_needs_no_external_key() -> None:
    data = example_data()
    assert edge_with(data, "offsite", data["hosts"]["edge"]["modules"]["offsite"]) == []
    manifest = manifest_from(data)
    assert "AYE_OFFSITE_ACCESS_KEY_ID" in generated(manifest, load_modules(), "edge", "offsite")


def test_conditions_drop_what_the_settings_do_not_use() -> None:
    data = example_data()
    assert edge_with(data, "cloudflare", {"accounts": ["a" * 32]}) == [
        "Cloudflare|custom API token, read only|AYE_CLOUDFLARE_ANALYTICS_TOKEN|"
        f"Account > Account Analytics > Read on account {'a' * 32}"
        " / no edit permission and no other zone or account"
    ]
    assert edge_with(data, "image-updates", {"ghcr_username": "octo"}) == [
        "GitHub|classic personal access token of octo|AYE_IMAGE_UPDATES_GHCR_TOKEN|"
        "scope read:packages only, to read the tags of private ghcr.io images"
    ]
    users = edge_with(data, "github", {"accounts": [{"user": "octo"}, {"org": "acme"}]})
    assert "classic scope user, for the billing usage of octo" in users[0]
    assert "organization acme: Administration read" in users[0]
    data["hosts"]["edge"]["modules"]["ai-usage"] = {"providers": ["openai"]}
    found = credentials(manifest_from(data), load_modules(), "edge", "ai-usage")
    assert [c.env for c in found] == [("AYE_OPENAI_ADMIN_KEY",)]


def test_the_cli_prints_the_permissions_or_refuses_a_broken_manifest(
    tmp_path: Path, capsys: pytest.CaptureFixture[str]
) -> None:
    assert main(["permissions", str(EXAMPLE)]) == 0
    assert capsys.readouterr().out.startswith("central\n  host access: aye host-init ")
    data = example_data()
    del data["services"]["web"]["description"]
    broken = tmp_path / "broken.yaml"
    broken.write_text(yaml.safe_dump(data), encoding="utf-8")
    assert main(["permissions", str(broken)]) == 1
    assert capsys.readouterr().err.splitlines()[-1] == (
        f"{broken}: no permissions, fix the errors first"
    )
